struct Directives {
  std::set<std::string> vars, includes;
};

// The #ifdef / #ifndef / #include arguments of one text, read the way
// ShaderPreprocessor::getSource reads them (a line is what SkipToNextLine
// leaves; the argument starts one byte after the keyword and ends at the next
// " \n\r\t").
Directives scan(const std::string& text)
{
  Directives d;
  auto ws = [](char ch) { return ch == ' ' || ch == '\n' || ch == '\r' || ch == '\t'; };
  std::size_t i = 0, n = text.size();
  while (i < n) {
    if (text[i] == '#') {
      std::size_t k = i;
      while (k < n && !ws(text[k])) ++k;
      std::string key = text.substr(i, k - i);
      if ((key == "#ifdef" || key == "#ifndef" || key == "#include") && k < n) {
        std::size_t a = k + 1, b = a;
        while (b < n && !ws(text[b])) ++b;
        (key == "#include" ? d.includes : d.vars).insert(text.substr(a, b - a));
      }
    }
    std::size_t e = i;
    while (e < n && text[e] != '\n' && text[e] != '\r' && text[e] != '\0') ++e;
    while (e < n && ws(text[e])) ++e;
    i = e;
  }
  return d;
}

// One set of shader texts (embedded, or read from disk) and a preprocessor on it.
struct Source {
  std::string kind;
  std::map<std::string, std::string> text;  // file name -> contents
  std::map<std::string, const char*> raw;   // what ShaderPreprocessor reads
  std::map<std::string, Directives> dir;
  std::set<std::string> all_vars;
  std::vector<std::string> variants;        // CallComputeColorForLight texts, "" first
  std::string default_variant;              // light_count 2, spec_count -1 (the defaults)
  PyMOLGlobals G;
  CFeedback fb;
  std::unique_ptr<ShaderPreprocessor> pp;

  void init()
  {
    for (auto& kv : text) {
      raw[kv.first] = kv.second.c_str();
      dir[kv.first] = scan(kv.second);
      all_vars.insert(dir[kv.first].vars.begin(), dir[kv.first].vars.end());
    }
    G.Feedback = &fb;
    pp.reset(new ShaderPreprocessor(&G, &raw));
  }

  void set_vars(const std::map<std::string, bool>& fixed, const std::vector<std::string>& free, std::uint64_t mask)
  {
    pp->clear();
    for (auto& v : all_vars)
      pp->setVar(v, false);
    for (auto& kv : fixed)
      pp->setVar(kv.first, kv.second);
    for (std::size_t i = 0; i < free.size(); ++i)
      pp->setVar(free[i], (mask >> i) & 1u);
  }

  void closure(const std::string& f, std::set<std::string>& vars, std::set<std::string>& seen, bool& call) const
  {
    if (!seen.insert(f).second)
      return;
    if (f == kCall) {
      call = true;
      return;
    }
    auto it = dir.find(f);
    if (it == dir.end())
      return;
    vars.insert(it->second.vars.begin(), it->second.vars.end());
    for (auto& inc : it->second.includes)
      closure(inc, vars, seen, call);
  }

  // CallComputeColorForLight: every template (its own closure) x light_count x
  // spec_count, plus "" (precomputed_lighting at reload: nothing set).
  void make_variants(const std::map<std::string, bool>& fixed)
  {
    std::set<std::string> tv, seen, uniq;
    bool call = false;
    closure("call_compute_color_for_light.fs", tv, seen, call);
    std::vector<std::string> free;
    for (auto& v : tv)
      if (!fixed.count(v)) free.push_back(v);
    variants = {""};
    for (std::uint64_t m = 0; m < (1ull << free.size()); ++m) {
      set_vars(fixed, free, m);
      std::string t = pp->getSource("call_compute_color_for_light.fs");
      if (m == 0) default_variant = call_compute_color_for_light(t, 2, -1);
      for (int lc = -1; lc <= 10; ++lc)
        for (int sc = -3; sc <= 10; ++sc) {
          std::string v = call_compute_color_for_light(t, lc, sc);
          if (uniq.insert(v).second) variants.push_back(v);
        }
    }
  }
};

std::string substitute(const std::string& s, const std::string& with)
{
  std::string r;
  std::size_t p = 0, m = std::string(kMarker).size();
  for (std::size_t q; (q = s.find(kMarker, p)) != std::string::npos; p = q + m)
    r.append(s, p, q - p).append(with);
  return r.append(s, p, std::string::npos);
}

// 128-bit fingerprint (two independent 64-bit hashes): the "checked once" set
// holds these instead of the strings.
struct Fp {
  std::uint64_t a, b;
  bool operator==(const Fp& o) const { return a == o.a && b == o.b; }
};
struct FpHash {
  std::size_t operator()(const Fp& f) const { return (std::size_t) (f.a ^ (f.b * 0x9E3779B97F4A7C15ull)); }
};
Fp fingerprint(const std::string& s, bool frag)
{
  std::uint64_t a = 14695981039346656037ull, b = 0x243F6A8885A308D3ull ^ s.size() ^ (frag ? 1 : 0);
  for (unsigned char c : s) {
    a = (a ^ c) * 1099511628211ull;
    b = (b + c + 1) * 0xC2B2AE3D27D4EB4Full;
    b ^= b >> 29;
  }
  return {a ^ (frag ? 0x5555555555555555ull : 0), b};
}

std::unordered_set<Fp, FpHash> g_seen;
bool g_ok_tables = true, g_ok_subst = true;
std::size_t g_subst_checks = 0, g_warned = 0;

enum { kAllTexts, kDefaultText, kDefaultAndEmpty };

struct Plan {
  std::string label;
  std::vector<std::string> files;
  std::map<std::string, bool> fixed;  // variables held at one value
  std::size_t max_masks = 0;          // 0: every combination of the others; else an even sample (0 and all-ones in it)
  int variants = kAllTexts;           // which CallComputeColorForLight texts
};

struct PlanTotals {
  std::size_t files = 0, combos = 0, unique = 0, expanded = 0, checked = 0;
};

std::vector<std::uint64_t> masks_for(std::size_t nfree, std::size_t max_masks)
{
  std::vector<std::uint64_t> r;
  std::uint64_t total = 1ull << nfree;
  if (max_masks == 0 || total <= max_masks) {
    for (std::uint64_t m = 0; m < total; ++m) r.push_back(m);
    return r;
  }
  for (std::size_t i = 0; i < max_masks; ++i)
    r.push_back((std::uint64_t) ((long double) i * (long double) (total - 1) / (long double) (max_masks - 1) + 0.5L));
  return r;
}

PlanTotals run_plan(Source& src, const Plan& plan, Counts& counts, bool verbose, std::vector<std::string>* keep)
{
  PlanTotals t;
  src.make_variants(plan.fixed);
  std::vector<std::string> variants = plan.variants == kAllTexts ? src.variants
      : plan.variants == kDefaultText ? std::vector<std::string>{src.default_variant}
      : std::vector<std::string>{"", src.default_variant};
  for (auto& f : plan.files) {
    if (!src.text.count(f)) {
      std::printf("%s: no file %s\n", plan.label.c_str(), f.c_str());
      g_ok_tables = false;
      continue;
    }
    std::set<std::string> vs, seen;
    bool call = false;
    src.closure(f, vs, seen, call);
    std::vector<std::string> free;
    for (auto& v : vs)
      if (!plan.fixed.count(v)) free.push_back(v);
    if (free.size() > 24) {
      std::printf("%s %s: %zu free variables, too many\n", plan.label.c_str(), f.c_str(), free.size());
      g_ok_tables = false;
      continue;
    }
    const bool frag = f.size() > 3 && f.compare(f.size() - 3, 3, ".fs") == 0;
    const auto masks = masks_for(free.size(), plan.max_masks);
    std::set<std::string> unique;  // ordered: a deterministic check order
    unsigned w0 = src.fb.warnings;
    for (auto m : masks) {
      src.set_vars(plan.fixed, free, m);
      src.pp->setSource(kCall, kMarker);
      unique.insert(src.pp->getSource(f));
    }
    if (src.fb.warnings != w0) {
      ++g_warned;
      std::printf("%s %s: the preprocessor warned (an #include it could not find)\n", plan.label.c_str(), f.c_str());
    }
    // Self-check: an include's processed text is inserted verbatim, so putting
    // a text in place of the marker equals preprocessing with that text.
    if (call) {
      for (std::size_t k = 0; k < masks.size(); k += masks.size() > 8 ? masks.size() / 8 : 1) {
        src.set_vars(plan.fixed, free, masks[k]);
        src.pp->setSource(kCall, kMarker);
        std::string marked = src.pp->getSource(f);
        for (auto& v : variants) {
          src.set_vars(plan.fixed, free, masks[k]);
          src.pp->setSource(kCall, v);
          ++g_subst_checks;
          if (src.pp->getSource(f) != substitute(marked, v)) {
            if (g_ok_subst)
              std::printf("SUBSTITUTION SELF-CHECK FAILED: %s %s\n", plan.label.c_str(), f.c_str());
            g_ok_subst = false;
          }
        }
      }
    }
    std::size_t expanded = 0, checked = 0;
    for (auto& u : unique) {
      const bool marked = u.find(kMarker) != std::string::npos;
      for (std::size_t k = 0; k < (marked ? variants.size() : 1); ++k) {
        std::string s = marked ? substitute(u, variants[k]) : u;
        ++expanded;
        if (!g_seen.insert(fingerprint(s, frag)).second)
          continue;
        ++checked;
        check(plan.label + " " + f, s, frag, counts);
        if (keep && keep->size() < 400 && (checked % 61) == 1) keep->push_back(s);
      }
    }
    if (verbose)
      std::printf("  %-28s vars %2zu free %2zu combos %6zu unique %5zu%s strings %6zu checked %6zu\n", f.c_str(), vs.size(),
          free.size(), masks.size(), unique.size(), call ? " +CCCFL" : "       ", expanded, checked);
    std::fflush(stdout);
    ++t.files; t.combos += masks.size(); t.unique += unique.size(); t.expanded += expanded; t.checked += checked;
  }
  std::printf("%s: files %zu, combinations %zu, unique preprocessed %zu, with CallComputeColorForLight texts %zu, checked (new) %zu\n",
      plan.label.c_str(), t.files, t.combos, t.unique, t.expanded, t.checked);
  std::fflush(stdout);
  return t;
}

