std::string escaped(const std::string& s, std::size_t from, std::size_t to)
{
  std::string r;
  char buf[8];
  for (std::size_t i = from; i < to && i < s.size(); ++i) {
    unsigned char c = (unsigned char) s[i];
    if (c == '\n') r += "\\n\n";
    else if (c == '\r') r += "\\r";
    else if (c == '\t') r += "\\t";
    else if (c == '\\') r += "\\\\";
    else if (c < 0x20 || c >= 0x7f) { std::snprintf(buf, sizeof buf, "\\x%02x", c); r += buf; }
    else r += (char) c;
  }
  return r;
}

void write_file(const std::string& name, const std::string& data)
{
  std::ofstream f(g_out_dir + "/" + name, std::ios::binary);
  f.write(data.data(), (std::streamsize) data.size());
}

void check(const std::string& label, const std::string& src, bool frag, Counts& c)
{
  ++c.strings;
  ++(frag ? c.frag : c.vert);
  c.bytes += src.size();
  if (g_count_only)
    return;
  const std::string o = old_es300(src, frag);
  const std::string n = pymolweb_es300_rewrite(src, frag);
  if (o != n) {
    if (g_diffs++ == 0) {
      std::size_t at = 0;
      while (at < o.size() && at < n.size() && o[at] == n[at]) ++at;
      std::printf("FIRST DIFFERENCE: %s (%s), input %zu bytes, old %zu bytes, new %zu bytes, first differing output byte %zu\n",
          label.c_str(), frag ? "fragment" : "non-fragment", src.size(), o.size(), n.size(), at);
      std::printf("--- input (escaped) ---\n%s\n", escaped(src, 0, src.size()).c_str());
      std::printf("--- old output (escaped) ---\n%s\n", escaped(o, 0, o.size()).c_str());
      std::printf("--- new output (escaped) ---\n%s\n--- end ---\n", escaped(n, 0, n.size()).c_str());
      write_file("first_diff.input.txt", src);
      write_file("first_diff.old.txt", o);
      write_file("first_diff.new.txt", n);
    }
    return;
  }
  for (unsigned r = 0; r < pymolweb_es300::kRuleCount; ++r) {
    // 200 detections of a rule per group are evidence enough; skip the rest
    if (c.ctl[r] < 200 && pymolweb_es300::rewrite_masked(src, frag, 1u << r) != o)
      ++c.ctl[r];
  }
}

