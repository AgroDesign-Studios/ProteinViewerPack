// ---- old: patch 0005's pymolweb_to_es300 without its GL calls --------------
// The GL part (the cached GL_VERSION check and glGetShaderiv(GL_SHADER_TYPE))
// stays in ShaderMgr.cpp; `frag` is `type == GL_FRAGMENT_SHADER` there. The
// lines from `std::string s =` to the last return are 0005's, verbatim
// (run_es300_rewrite_test.sh checks this against the patch file).
static std::string old_es300(const std::string& src, bool frag)
{
  std::string s = std::regex_replace(src, std::regex(R"(^[ \t]*#(version|extension)[^\n]*)", std::regex::multiline), "");
  s = std::regex_replace(s, std::regex(R"(^[ \t]*#define[ \t]+texture[ \t]+texture2D[^\n]*)", std::regex::multiline), "");
  s = std::regex_replace(s, std::regex(R"(\btexture2D\s*\()"), "texture(");
  s = std::regex_replace(s, std::regex(R"(\btextureCube\s*\()"), "texture(");
  s = std::regex_replace(s, std::regex(R"(\bvarying\b)"), frag ? "in" : "out");
  if (frag) {
    s = std::regex_replace(s, std::regex(R"(\bgl_FragColor\b|\bgl_FragData\s*\[\s*0\s*\])"), "pymolweb_FragColor");
    s = std::regex_replace(s, std::regex(R"(\bgl_FragDepthEXT\b)"), "gl_FragDepth");
    return "#version 300 es\nprecision highp float;\nout vec4 pymolweb_FragColor;\n" + s;
  }
  s = std::regex_replace(s, std::regex(R"(\battribute\b)"), "in");
  return "#version 300 es\n" + s;
}

// ---- ShaderMgr.cpp's CallComputeColorForLight assembly, copied --------------
static std::string stringReplaceAll(const std::string &src, const std::string * replaceStrings) {
  std::string dest = src;
  for (int i = 0; !replaceStrings[i].empty(); i += 2) {
    int slen1 = replaceStrings[i].length();
    int slen2 = replaceStrings[i + 1].length();
    for (size_t pl = 0;
        (pl = dest.find(replaceStrings[i], pl)) != std::string::npos;
        pl += slen2) {
      dest.replace(pl, slen1, replaceStrings[i + 1]);
    }
  }
  return dest;
}

// CShaderMgr::Reload_CallComputeColorForLight's text for one light_count /
// spec_count (its precomputed_lighting branch sets nothing: the "" variant).
static std::string call_compute_color_for_light(const std::string& rawtemplate, int light_count, int spec_count)
{
  std::ostringstream accstr;
  std::string lightstrings[] = {
    "`light`", "0",
    "`postfix`", "_0",
    ""
  };
  accstr << stringReplaceAll(rawtemplate, lightstrings);
  if (light_count > 8){
    light_count = 8;
  }
  lightstrings[3] = "";
  for (int i=1; i<light_count; i++){
    std::ostringstream lstr;
    lstr << i;
    lightstrings[1] = lstr.str();
    if (i == spec_count + 1) {
      lightstrings[3] = " * 0.0";
    }
    accstr << stringReplaceAll(rawtemplate, lightstrings);
  }
  return accstr.str();
}

